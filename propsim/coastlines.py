"""Simplified world coastlines, as (longitude, latitude) rings.

Used for two things at once, which is why they live here rather than in a
map file: :mod:`propsim.surface` decides from them whether a ground
reflection lands on sea water or on soil, and the web globe draws them.  What
you see is therefore the surface the model actually reflects off, not a
prettier basemap that disagrees with it.

These are hand-simplified outlines at roughly 1:110 million detail -- enough
to place a mid-path ground bounce on the right side of a coastline, which is
all the reflection loss depends on.  They are not a survey product and should
not be used as one.  Known simplifications, all of them deliberate:

* Hudson Bay, the Baltic, the Black Sea, the Caspian and the Persian Gulf are
  treated as land.  Each is small against a hop length and enclosed by the
  landmass around it.
* Rings never cross the antimeridian, because the point-in-polygon test and
  the globe projection both assume longitudes inside one -180..180 span.
* Antarctica is closed through the pole rather than traced round it.
"""

